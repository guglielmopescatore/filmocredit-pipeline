"""
Prepare one block-B run (scroll cap) as an isolated git worktree.

Creates runs/<prefix>_cap<N> at the pinned commit for one folder set (see
SETS: the 14 roll titles, the 6 titles without rolls, or the hold-out), without
the reference episode folders and databases, then fills it with:
  - scripts_v3/config.py: SCROLL_MAX_FRAMES_PER_SAVE = N (the only code change;
    none for N = 150, the reference value);
  - data/episodes/<folder>/analysis/: the reference Stage I outputs
    raw_scenes_cache.json and initial_scene_analysis.json only (frames/ and
    analysis_manifest.json are regenerated by Stage II);
  - data/raw/<corpus>/: copies of the set's clips;
  - db/: IMDb files only, no .db; .env copied from the main checkout;
  - run_info.json with commit, code change, parameters, stopwords and the
    reference Stage II frames of the set.

Stage II, III and IV are run by run_headless.py, which fills the submitted
frames into run_info.json after Stage II together with the comparison against
the reference. The reference Stage II was made with other code/environment
(00f0cbc5 for the main corpus, pre-5fec349 for the hold-out), so a difference
is recorded, never a reason to stop.

No model call is made here.

Usage:
    python prepare_pipe_run.py --cap 150                   # runs/PIPE_cap150 (14 roll titles)
    python prepare_pipe_run.py --cap 150 --set noscroll    # runs/PIPE_noscroll_cap150 (6 titles)
    python prepare_pipe_run.py --cap 150 --set holdout     # runs/STAGE2_holdout_cap150 (Stage II check)
    python prepare_pipe_run.py --cap 100 --set ypm         # runs/PIPE_noscroll_cap100 (YPM only)
"""


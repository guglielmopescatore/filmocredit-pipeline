def set_cap(run_dir: Path, cap: int) -> list[str]:
    if cap == JULY_CAP:
        return []
    config_py = run_dir / "scripts_v3" / "config.py"
    text = config_py.read_text(encoding="utf-8")
    old, new = CAP_LINE.format(JULY_CAP), CAP_LINE.format(cap)
    if text.count(old) != 1:
        sys.exit(f"Expected exactly one '{old}' in {config_py}")
    config_py.write_text(text.replace(old, new), encoding="utf-8")
    return [git("diff", "--", "scripts_v3/config.py", cwd=run_dir)]


def copy_stage1(run_dir: Path, folders: list[str]) -> None:
    for folder in folders:
        src = MAIN_ROOT / "data" / "episodes" / folder / "analysis"
        dst = run_dir / "data" / "episodes" / folder / "analysis"
        dst.mkdir(parents=True)
        for name in STAGE1_FILES:
            shutil.copy2(src / name, dst / name)


def reference_frames(folder_set: dict) -> dict[str, list[str]]:
    frames = {
        f: sorted(p.name for p in (MAIN_ROOT / "data" / "episodes" / f / "analysis" / "frames").glob("*.jpg"))
        for f in folder_set["folders"]
    }
    total = sum(map(len, frames.values()))
    if total != folder_set["expected_reference"]:
        sys.exit(f"Reference has {total} frames, expected {folder_set['expected_reference']}")
    return frames


def write_run_info(run_dir: Path, run_id: str, cap: int, set_name: str, code_diff: list[str]) -> None:
    folder_set = SETS[set_name]
    folders = folder_set["folders"]
    info = {
        "run_id": run_id,
        "block": "B - scroll cap" if set_name != "holdout" else "Stage II check on the hold-out (no Stage III)",
        "folder_set": set_name,
        **({"composition": folder_set["composition"]} if "composition" in folder_set else {}),
        "prepared_at": datetime.now(timezone.utc).isoformat(),
        "git_commit": git("rev-parse", "HEAD", cwd=run_dir),
        "code_modifications": code_diff,
        "parameters": {
            "SCROLL_MAX_FRAMES_PER_SAVE": cap,
            "stages": ["stage2", "stage3", "stage4"],
            "naive_mode": False,
            "stage1": "not rerun: reference raw_scenes_cache.json + initial_scene_analysis.json copied",
            "stage2_scenes": "all candidate scenes of initial_scene_analysis.json, in file order (as in the reference)",
            "ocr_engine": "paddleocr",
            # The reference Stage II (Dec 2025 main corpus, Jul 2026 hold-out) used lang="en"
            # (en_PP-OCRv5_mobile_rec); "it" loads latin_PP-OCRv5_mobile_rec and selects other frames.
            "ocr_language": OCR_LANGUAGE,
            **model_params(run_dir),
        },
        "source": {
            "stage1_from": f"data/episodes/<folder>/analysis at commit {RUN_COMMIT}",
            "reference_stage2": folder_set["reference"],
            "july_reference_db": "db/FUZZY88_GPT_SOL_STANDARD_25products_tvcredits_v3.db",
        },
        "stopwords": stopwords_info(run_dir),
        "pricing_usd_per_1M_tokens": PRICING_USD_PER_1M,
        "expected_export_csv": f"{run_id}_FUZZY88_GPT_SOL_STANDARD_{folder_set['products']}products.csv",
        # The reference Stage II predates 5fec349: compare, never stop.
        "stop_if_stage2_differs_from_reference": False,
        "reference_note": REFERENCE_NOTE,
        "reference_frames_total": folder_set["expected_reference"],
        "reference_frames": reference_frames(folder_set),
        # Filled by run_headless.py after Stage II.
        "submitted_frames_total": None,
        "submitted_frames": {f: None for f in folders},
    }
    (run_dir / "run_info.json").write_text(json.dumps(info, indent=2, ensure_ascii=False), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cap", type=int, required=True)
    parser.add_argument("--set", dest="set_name", choices=sorted(SETS), default="scroll")
    args = parser.parse_args()
    cap, set_name = args.cap, args.set_name

    run_id = f"{SETS[set_name]['prefix']}_cap{cap}"
    run_dir = MAIN_ROOT / "runs" / run_id
    if run_dir.exists():
        sys.exit(f"{run_dir} already exists: a run is never overwritten")

    folders = SETS[set_name]["folders"]
    create_worktree(run_dir)
    code_diff = set_cap(run_dir, cap)
    copy_stage1(run_dir, folders)
    copy_support_files(run_dir, folders, SETS[set_name]["corpus"])
    write_run_info(run_dir, run_id, cap, set_name, code_diff)
    print(f"{run_id}: prepared, set={set_name}, cap={cap}, code changes: {len(code_diff)}")


if __name__ == "__main__":
    main()
